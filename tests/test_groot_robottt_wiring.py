def test_flatten_is_window_major_and_drops_sequence_only_keys():
    flat, batch, length = flatten_window_batch(_batch(), L)
    assert (batch, length) == (B, L)

    # Flat index b*L + t must be window b's step t — checked on the value tags, not the shapes.
    assert list(flat["state"].shape) == FIXTURE["flat"]["state"]
    assert list(flat["action"].shape) == FIXTURE["flat"]["action"]
    for b in range(B):
        for t in range(L):
            assert float(flat["state"][b * L + t, 0, 0]) == float(b * L + t)
            assert float(flat["action"][b * L + t, 0, 0]) == float(b * L + t)

    # Keys the head consumes itself must not reach the vendored forward.
    for key in ("seq_len", "seq_window_len", "loss_mask", "reset"):
        assert key not in flat
    # Non-windowed keys pass through untouched.
    assert tuple(flat["embodiment_id"].shape) == (B * L,)


def test_flatten_rejects_a_batch_with_no_window_axis():
    """A batch that lost its window axis means the sequence collator did not run."""
    bad = _batch()
    bad["state"] = torch.zeros(B, L + 1, HIST, S // HIST)
    with pytest.raises(ValueError, match="expected a window axis"):
        flatten_window_batch(bad, L)


class _TaggingFastWeights:
    """Stand-in whose output at step t of window b is the scalar (b*L + t), i.e. the flat index."""

    def run_sequence(self, state_seq, action_seq):
        batch, length = state_seq.shape[0], state_seq.shape[1]
        out = torch.zeros(length, batch, C)
        for b in range(batch):
            for t in range(length):
                out[t, b, :] = float(b * length + t)
        return out, {"w2": torch.zeros(batch, 3, 3)}


def test_conditioning_order_matches_the_flatten_order():
    """The invariant: cond[b*L + t] is window b step t — the same index the flatten produced."""
    flat, batch, length = flatten_window_batch(_batch(), L)
    cond, _ = sequence_conditioning(_TaggingFastWeights(), torch.zeros(B, L, S), torch.zeros(B, L, H, A))

    assert tuple(cond.shape) == (B * L, C)
    for b in range(B):
        for t in range(L):
            i = b * L + t
            assert float(cond[i, 0]) == float(i)
            # and it agrees with the observation that landed at the same flat index
            assert float(flat["state"][i, 0, 0]) == float(i)


def test_step_major_conditioning_is_distinguishable():
    """Non-vacuity: the transposed order must differ, or the test above proves nothing."""
    out_seq, _ = _TaggingFastWeights().run_sequence(torch.zeros(B, L, S), torch.zeros(B, L, H, A))
    window_major = out_seq.permute(1, 0, 2).reshape(B * L, C)
    step_major = out_seq.reshape(B * L, C)  # the tempting, WRONG line
    assert not torch.equal(window_major, step_major)


def test_real_module_roll_is_finite_and_apply_then_commit():
    """The real module through the same seam: finite output, and step 0 sees the ENTERING W_0.

    With the readout zero-initialised, O_0 must be exactly zero — that is the observable signature
    of apply-then-commit (D-1). If the wiring committed first, step 0 would be conditioned by W_1
    and, because the readout is zero at init, still be zero — so the test also perturbs the readout
    and checks O_0 is the value produced by W_0 rather than by W_1.
    """
    from workspace_models.networks.robottt_fast_weights import RoboTTTFastWeights

    torch.manual_seed(0)
    mod = RoboTTTFastWeights(_cfg(token_dim=32, fast_hidden=16, num_registers=4, window_len=L, tbptt_segment=L))
    with torch.no_grad():  # break the zero-init so O_t can be non-trivial
        mod.readout.weight.normal_(0, 0.1)
        mod.alpha.fill_(0.5)

    state_seq = torch.randn(B, L, S)
    action_seq = torch.randn(B, L, H, A)
    cond, w_final = sequence_conditioning(mod, state_seq, action_seq)
    assert tuple(cond.shape) == (B * L, C)
    assert torch.isfinite(cond).all()

    # O_0 must equal condition(W_0, s_0): the entering state, not the post-commit one.
    expected_0 = mod.condition(mod.init_state(B), state_seq[:, 0])
    torch.testing.assert_close(cond[0::L], expected_0, rtol=1e-5, atol=1e-6)
    committed = mod.commit(mod.init_state(B), state_seq[:, 0], action_seq[:, 0])
    assert not torch.allclose(mod.condition(committed, state_seq[:, 0]), expected_0), (
        "conditioning is identical before and after a commit — this fixture cannot tell "
        "apply-then-commit from commit-then-apply"
    )
    for leaf in w_final.values():
        assert torch.isfinite(leaf).all()


def test_tbptt_truncation_changes_gradients_but_not_forward_values():
    """G affects gradients only. Pinned at the MEASURED widths, where the roll is 40x wider than the
    toy fixture this used to run at — the forward equality is what lets G be a memory knob."""
    from workspace_models.networks.robottt_fast_weights import RoboTTTFastWeights

    torch.manual_seed(0)
    mod = RoboTTTFastWeights(_cfg(token_dim=32, fast_hidden=16, num_registers=4, window_len=L, tbptt_segment=L))
    with torch.no_grad():
        mod.readout.weight.normal_(0, 0.1)
        mod.alpha.fill_(0.5)
    state_seq, action_seq = torch.randn(B, L, S), torch.randn(B, L, H, A)

    full, _ = mod.run_sequence(state_seq, action_seq, tbptt_segment=L)
    cut, _ = mod.run_sequence(state_seq, action_seq, tbptt_segment=1)
    torch.testing.assert_close(full, cut, rtol=1e-6, atol=1e-7)

    grad_full = torch.autograd.grad(full.sum(), mod.w0_w1, retain_graph=True)[0]
    grad_cut = torch.autograd.grad(cut.sum(), mod.w0_w1)[0]
    assert not torch.allclose(grad_full, grad_cut), (
        "truncating BPTT to G=1 left the gradient to W_0 unchanged — the carry is not in the graph"
    )


def test_serve_reset_commit_cycle_is_finite_at_production_dims():
    """Serve-order regression at PRODUCTION geometry: reset -> (condition, commit) x 32, all finite.

    Same reason `test_stability_at_production_dims` exists on the module: the toy dims that unit
    tests default to are stable under an inner step that diverges at d=256/h=128. "Production dims"
    now means the MEASURED ones — d=256, h=128, C=1536, state 132, action 40x132 — rather than a
    number typed into this file, which is the second half of the same lesson.
    """
    from workspace_models.networks.robottt_fast_weights import RoboTTTFastWeights

    torch.manual_seed(0)
    mod = RoboTTTFastWeights(_cfg()).eval()
    assert (mod.cfg.token_dim, mod.cfg.fast_hidden) == (256, 128), mod.cfg
    assert mod.state_in.in_features == S and mod.action_in.in_features == A

    w = mod.init_state(2)
    for step in range(32):
        state = torch.randn(2, S)
        cond = mod.condition(w, state)
        assert torch.isfinite(cond).all(), f"conditioning went non-finite at serve step {step}"
        w = mod.commit(w, state, torch.randn(2, H, A))
        for name, leaf in w.items():
            assert torch.isfinite(leaf).all(), f"fast weight {name} diverged at serve step {step}"
    assert float(w["w2"].abs().max()) < 1e3, "fast weights growing without bound"


def test_env_config_reads_the_documented_knobs(monkeypatch):
    from vla_training.train.train_base._groot_robottt_common import robottt_config_from_env

    for key, value in {
        "WSM_TTT_TOKEN_DIM": "128",
        "WSM_TTT_FAST_HIDDEN": "64",
        "WSM_TTT_NUM_REGISTERS": "8",
        "WSM_TTT_INNER_LR": "0.05",
        "WSM_TTT_GATE_INIT": "1e-4",
        "WSM_SEQ_WINDOW_LEN": "6",
    }.items():
        monkeypatch.setenv(key, value)
    cfg = robottt_config_from_env(
        cond_dim=C,
        dims_source=DIMS["dims_source"],
        **{k: DIMS[k] for k in ("state_dim", "action_dim", "action_horizon")},
    )
    assert (cfg.token_dim, cfg.fast_hidden, cfg.num_registers) == (128, 64, 8)
    assert cfg.base_inner_lr == 0.05 and cfg.gate_init == 1e-4
    # G defaults to L, i.e. full BPTT over the window unless explicitly truncated.
    assert cfg.window_len == 6 and cfg.tbptt_segment == 6
    assert cfg.cond_dim == C
    # The widths pass through UNTOUCHED and carry their provenance: no env knob is consulted for
    # them unless one is set, and the ttt yamls set none.
    assert (cfg.state_dim, cfg.action_dim, cfg.action_horizon) == (S, A, H)
    assert "robottt_seam_dims" in cfg.dims_source and "OVERRIDE" not in cfg.dims_source


def test_a_width_override_is_recorded_in_the_provenance(monkeypatch):
    """The escape hatch exists, but it may not hide: the override lands in `dims_source`, so the
    shape error it eventually causes blames the override and not the derivation."""
    from vla_training.train.train_base._groot_robottt_common import robottt_config_from_env

    monkeypatch.setenv("WSM_TTT_STATE_DIM", "64")
    cfg = robottt_config_from_env(
        cond_dim=C,
        dims_source=DIMS["dims_source"],
        **{k: DIMS[k] for k in ("state_dim", "action_dim", "action_horizon")},
    )
    assert cfg.state_dim == 64
    assert "OVERRIDES" in cfg.dims_source and "'state_dim': (132, 64)" in cfg.dims_source


