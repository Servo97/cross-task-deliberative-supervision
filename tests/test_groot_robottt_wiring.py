def test_derived_dims_reproduce_the_measured_collated_tensors():
    """The whole point: the derivation and the real collator agree, so this file's dims are real."""
    seam, collated = FIXTURE["seam"], FIXTURE["collated"]
    assert [B, L, S] == seam["state_seq"], (DIMS, seam)
    assert [B, L, H, A] == seam["action_seq"], (DIMS, seam)
    # ...and the pre-flatten tensor really is [B, L, state_history_length, max_state_dim], i.e. the
    # head's `state.reshape(B, L, -1)` is a flatten of the history axis and not a lucky no-op.
    assert collated["state"] == [B, L, HIST, S // HIST]
    assert S == HIST * FIXTURE["processor"]["max_state_dim"]
    # The RoboCasa modality carries 16 real action steps x 12 real channels; the seam sees the
    # PADDED [40, 132] block. Reading H off the modality config instead of the processor is the
    # near-miss this pins.
    assert H != FIXTURE["raw_modality"]["action_timesteps"]
    assert A != FIXTURE["raw_modality"]["action_channels"]


def test_the_config_has_no_width_defaults_left_to_inherit():
    """The canary's root cause, pinned: a RoboTTTConfig without derived widths must not exist."""
    import dataclasses

    from workspace_models.networks.robottt_fast_weights import RoboTTTConfig

    with pytest.raises(ValueError, match=r"missing the data-determined width"):
        RoboTTTConfig(token_dim=16, fast_hidden=8, num_registers=4, cond_dim=C)
    for field in ("state_dim", "action_dim", "action_horizon"):
        with pytest.raises(ValueError, match=field):
            dataclasses.replace(_cfg(), **{field: -1})


def test_seam_dims_refuses_to_guess_when_the_metadata_is_absent():
    """No fallback path. `attach_robottt` used to answer 64 here, from a `hasattr` that was False."""
    with pytest.raises(AttributeError, match="max_state_dim"):
        robottt_seam_dims(_Meta(), _model_config())
    with pytest.raises(AttributeError, match="state_history_length"):
        robottt_seam_dims(_processor(), _Meta(max_state_dim=132, max_action_dim=132, action_horizon=40))


def test_seam_dims_rejects_a_processor_that_disagrees_with_the_model_config():
    """On the `start_from_checkpoint` path these come from two different files and CAN drift."""
    with pytest.raises(ValueError, match=r"max_state_dim=64 disagrees .*max_state_dim=132"):
        robottt_seam_dims(_processor(max_state_dim=64), _model_config())
    with pytest.raises(ValueError, match=r"max_action_horizon=16 disagrees .*action_horizon=40"):
        robottt_seam_dims(_processor(max_action_horizon=16), _model_config())


def test_a_width_mismatch_fails_loud_and_names_both_numbers_and_the_source():
    """The exact canary failure, reproduced — and now caught before `nn.Linear` mangles it.

    `mat1 and mat2 shapes cannot be multiplied (2x132 and 64x256)` names neither field nor side nor
    provenance. These messages name the tensor width, the cfg width, and where the cfg came from.
    """
    from workspace_models.networks.robottt_fast_weights import RoboTTTFastWeights

    stale = _cfg(
        token_dim=32,
        fast_hidden=16,
        num_registers=4,
        state_dim=64,
        action_dim=32,
        action_horizon=16,
        dims_source="RoboTTTConfig pi-lineage defaults",
    )
    mod = RoboTTTFastWeights(stale)
    with pytest.raises(ValueError, match=r"state width .*132.*cfg\.state_dim=64"):
        mod.condition(mod.init_state(B), torch.zeros(B, S))
    with pytest.raises(ValueError, match="pi-lineage defaults"):
        mod.condition(mod.init_state(B), torch.zeros(B, S))

    good_state = _cfg(token_dim=32, fast_hidden=16, num_registers=4, action_dim=32)
    mod = RoboTTTFastWeights(good_state)
    with pytest.raises(ValueError, match=r"action width .*132.*cfg\.action_dim=32"):
        mod.commit(mod.init_state(B), torch.zeros(B, S), torch.zeros(B, H, A))

    good_dim = _cfg(token_dim=32, fast_hidden=16, num_registers=4, action_horizon=16)
    mod = RoboTTTFastWeights(good_dim)
    with pytest.raises(ValueError, match=r"action horizon .*40.*cfg\.action_horizon=16"):
        mod.commit(mod.init_state(B), torch.zeros(B, S), torch.zeros(B, H, A))


