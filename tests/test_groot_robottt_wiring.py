"""RoboTTT GR00T action-head wiring: the window-major pairing, the derived widths, the guards.

The port's other tests cover the fast-weight MATH (`test_groot_robottt_fast_weights.py`) and the
window ENUMERATION (`test_groot_seq_windows.py`). This file covers the seam between them: how a
`[B, L, ...]` sequence batch is flattened to `B*L`, how the `[L, B, C]` conditioning is put in the
SAME order, and — since 2026-08-08 — where the fast weights' input widths come from.

TWO FAILURE MODES, BOTH SILENT-BY-DEFAULT, BOTH PINNED HERE.

1. THE PAIRING. The right and wrong flatten orders have identical shapes, both train, and both
   produce a falling loss; the wrong one just pairs every observation with another timestep's
   fast-weight state. So the tests carry per-(window, step) TAGS through both paths and assert
   element-wise identity, plus that the transposed arrangement does NOT match.

2. THE WIDTHS. The first TTT canary died at step 0 on `mat1 and mat2 shapes cannot be multiplied
   (2x132 and 64x256)`: `state_in` had been built at `RoboTTTConfig`'s pi-lineage default
   `state_dim=64` while the real GR00T processor pads proprio to `max_state_dim=132`. The eight
   tests in this file all passed, because every one of them synthesised its tensors AT the config
   dims — the test and the code agreed with each other and neither had ever met the data. The fix
   is structural, not a corrected constant: `DIMS` below is produced by the PRODUCTION function
   `robottt_seam_dims`, fed the metadata MEASURED off the real processor and the real collator
   (`tests/fixtures/groot_n17_seam_dims.json`, regenerated by
   `tests/fixtures/extract_groot_seam_dims.py` in the gr00t venv). For a test here to pass at a
   width the data does not have, the fixture would have to be wrong — and the extractor asserts the
   derivation against the collated tensors, so a wrong fixture cannot be written.

Pure-torch: no gr00t import, runs in the same venv as the rest of the port's tests.
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import numpy as np
import pytest
import torch

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from vla_training.train.train_base._groot_robottt_common import (  # noqa: E402
    flatten_window_batch,
    robottt_seam_dims,
    sequence_conditioning,
)

FIXTURE = json.loads((Path(__file__).parent / "fixtures" / "groot_n17_seam_dims.json").read_text())


class _Meta:
    """A stand-in carrying only the attributes `robottt_seam_dims` reads off the real objects."""

    def __init__(self, **fields):
        self.__dict__.update(fields)


def _processor(**over):
    return _Meta(**{**FIXTURE["processor"], **over})


def _model_config(**over):
    fields = {k: v for k, v in FIXTURE["model_config"].items() if k != "input_embedding_dim"}
    return _Meta(**{**fields, **over})


#: THE DIMS EVERY FIXTURE BELOW IS BUILT FROM — the production derivation over measured metadata.
DIMS = robottt_seam_dims(_processor(), _model_config())
S = DIMS["state_dim"]  # 132 = state_history_length(1) * max_state_dim(132)
A = DIMS["action_dim"]  # 132 = max_action_dim
H = DIMS["action_horizon"]  # 40  = max_action_horizon (the PADDED chunk length)
HIST = DIMS["state_history_length"]  # 1
C = FIXTURE["cond_dim"]  # 1536 = the DiT inner width the readout rides
B, L = FIXTURE["collated"]["B"], FIXTURE["collated"]["L"]


def _batch():
    """A sequence batch whose every entry ENCODES its own (window, step) index, at MEASURED widths.

    state[b, t] is all-(b*L + t), so a transposition is visible in the values rather than only in a
    shape, which is the only way a test can see that class of bug.
    """
    tag = torch.arange(B * L, dtype=torch.float32).reshape(B, L)
    return {
        "state": (tag[:, :, None, None] + torch.zeros(B, L, HIST, S // HIST)),
        "action": (tag[:, :, None, None] + torch.zeros(B, L, H, A)),
        "action_mask": torch.ones(B, L, H, A, dtype=torch.bool),
        "embodiment_id": torch.full((B, L), 10, dtype=torch.long),
        "seq_window_len": torch.tensor(L),
        "seq_len": torch.full((B, L), L, dtype=torch.long),
        "loss_mask": torch.ones(B, L),
        "reset": torch.zeros(B, L, dtype=torch.bool),
    }


def _cfg(**over):
    """The production config builder, at the derived widths. Tests never hand-write a width."""
    import dataclasses

    from vla_training.train.train_base._groot_robottt_common import robottt_config_from_env

    cfg = robottt_config_from_env(
        cond_dim=C, state_dim=S, action_dim=A, action_horizon=H, dims_source=DIMS["dims_source"]
    )
    return dataclasses.replace(cfg, **over) if over else cfg


